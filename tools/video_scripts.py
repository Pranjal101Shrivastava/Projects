"""Generate a spoken script for one walkthrough video per project.

Run:
    python3 tools/video_scripts.py

Same rule as tools/docs.py and tools/readme.py: every figure spoken aloud in these scripts
is read from a committed artifact rather than typed. A presenter reading one of these on
camera is therefore saying the same number the site is displaying behind them, and a rerun
of a pipeline updates the script rather than leaving the video contradicting the screen.

Each script is written to be *said*, not read: short sentences, one idea per breath,
contractions, and no clause that needs a second pass to parse. Stage directions are marked
separately from speech so they are never read out by mistake.

Timestamps are computed from a cumulative word count at SPEAKING_WPM, so they shift
automatically when the numbers underneath them change.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from docs import SITE, SLUGS, load, pct  # noqa: E402

OUT = ROOT / "docs" / "video-scripts"

# Unhurried presentation pace. Deliberately below conversational speed: these scripts are
# dense with figures, and a listener needs a beat after each one.
SPEAKING_WPM = 135


@dataclass
class Beat:
    """One spoken passage, with what should be visible while it is said."""
    heading: str
    say: str
    show: str | None = None
    note: str | None = None


def _words(text: str) -> int:
    return len(re.findall(r"[\w'’-]+", text))


def _clock(seconds: float) -> str:
    return f"{int(seconds) // 60}:{int(seconds) % 60:02d}"


def render(project: str, title: str, hook: str, prep: list[str], beats: list[Beat]) -> str:
    """Assemble one script, timestamping each beat from the words spoken before it."""
    slug = SLUGS[project]
    spoken = 0
    body: list[str] = []

    for beat in beats:
        body.append(f"## [{_clock(spoken / SPEAKING_WPM * 60)}] {beat.heading}")
        body.append("")
        if beat.show:
            body.append(f"> **On screen —** {beat.show}")
            body.append("")
        if beat.note:
            body.append(f"> **Note to self —** {beat.note}")
            body.append("")
        body.append(beat.say.strip())
        body.append("")
        spoken += _words(beat.say)

    total_words = spoken
    runtime = _clock(total_words / SPEAKING_WPM * 60)

    prep_lines = "\n".join(f"- {p}" for p in prep)

    return f"""# Video {project[:2]} · {title}

**Estimated runtime:** ~{runtime} at a measured pace ({total_words:,} spoken words)
**Live page:** {SITE}/#/p/{slug}
**Project directory:** [`projects/{project}/`](../../projects/{project}/)

> **The one sentence this video has to land:** {hook}

## Before you record

{prep_lines}

Everything in plain text below is meant to be **spoken**. Lines marked *On screen* and
*Note to self* are directions — do not read them aloud.

---

{chr(10).join(body)}---

*Generated by [`tools/video_scripts.py`](../../tools/video_scripts.py) from committed
artifacts. Every figure spoken here is the figure on screen.*
"""


