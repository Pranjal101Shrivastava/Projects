def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    written: list[tuple[str, str, int]] = []
    total_words = 0

    for generator in GENERATORS:
        project, content = generator()
        path = OUT / f"{project}.md"
        path.write_text(content)

        title = content.splitlines()[0].split("·", 1)[1].strip()
        runtime = content.split("**Estimated runtime:** ~")[1].split(" ")[0]
        words = int(content.split("(")[1].split(" spoken")[0].replace(",", ""))
        total_words += words
        written.append((project, title, runtime))
        print(f"  {path.relative_to(ROOT)}  (~{runtime}, {words:,} words)")

    (OUT / "README.md").write_text(index(written))
    minutes = total_words / SPEAKING_WPM
    print(f"\nWrote {len(written)} scripts + an index to {OUT.relative_to(ROOT)}")
